def h(v):
    return "0x%08x" % v


def lines_of(path):
    with open(os.path.join(ROOT, path), encoding="utf-8") as f:
        return f.read().splitlines()


def find(path, pattern, start=0):
    """path:line of the first line matching pattern."""
    for i, line in enumerate(lines_of(path), 1):
        if i > start and re.search(pattern, line):
            return "%s:%d" % (path, i)
    return path


def yaml_devices(path, section):
    """{name: (number, comment, line)} of a generated device file."""
    out, name = {}, None
    for i, line in enumerate(lines_of(path), 1):
        m = re.match(r"  ([a-z0-9_]+):\s*$", line)
        if m:
            name = m.group(1)
            out[name] = {"line": i}
            continue
        m = re.match(r"    number: (\S+)\s*(?:#\s*(.*))?$", line)
        if m and name:
            out[name].update(number=m.group(1), comment=(m.group(2) or "").strip())
        m = re.match(r"    (default_pulse_ms|default_hold_power): (\S+)", line)
        if m and name:
            out[name][m.group(1)] = m.group(2)
    return out


