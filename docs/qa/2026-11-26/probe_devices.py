def sw_record(addr):
    hnd, arg, nm, _ = struct.unpack_from("<4I", rom.ROM, rom.foff(addr))
    return dict(handler=hnd, arg=arg, name=rom.cstr(rom.u32(nm)) if nm else "", tflags=rom.u16(addr + 0xc),
                mask=rom.u16(addr + 0xe), w10=rom.u16(addr + 0x10), w12=rom.u16(addr + 0x12), task=rom.u16(addr + 0x14),
                close=rom.u8(addr + 0x1b), open=rom.u8(addr + 0x1c))


def edges(mask):
    e = []
    if mask & 0x400:
        e.append("close")
    if mask & 0x800:
        e.append("open")
    return "+".join(e) or "none"


